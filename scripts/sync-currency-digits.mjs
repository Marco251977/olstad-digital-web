// The minor-unit digits per currency (ISO 4217) – ONE table, the same as the apps and Saldo's server: app-core's
// ISO_CURRENCY_DIGITS (generated there from ISO 4217, read by minorDigits). Copied here unchanged as
// assets/currency-digits.js, because the admin page runs in the browser and cannot load the app-core package. Never typed
// in on the website; Intl alone is never the source (Intl gives IQD 0, ISO 3 – a price would be 10 times too high).
//   node scripts/sync-currency-digits.mjs          write the file from the installed app-core
//   node scripts/sync-currency-digits.mjs --check  stop (exit 1) when the file differs from app-core, or from Saldo's
//                                                  server table (supabase/functions/_shared/currency-digits.json, read with
//                                                  `git show` – the Saldo checkout is never touched; when the Saldo repo
//                                                  or the file is not on this machine, e.g. Vercel, say so and pass)
// Saldo repo: SALDO_REPO, else ../Apper/Saldo Pocket. Ref: SALDO_REF, else main, else feat/subscription-notice.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { ISO_CURRENCY_DIGITS } from 'app-core';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TARGET = 'assets/currency-digits.js';
const SALDO_FILE = 'supabase/functions/_shared/currency-digits.json';
const saldoRepo = process.env.SALDO_REPO ?? path.resolve(root, '../Apper/Saldo Pocket');
const saldoRefs = process.env.SALDO_REF ? [process.env.SALDO_REF] : ['main', 'feat/subscription-notice'];
const lf = (s) => s.replace(/\r\n/g, '\n');

/** The file as it should be: a module the browser and Node both import. */
export function currencyDigitsModule(table = ISO_CURRENCY_DIGITS) {
  const sorted = Object.fromEntries(Object.keys(table).sort().map((c) => [c, table[c]]));
  return [
    '// Generated by scripts/sync-currency-digits.mjs from app-core ISO_CURRENCY_DIGITS (ISO 4217). Do not edit.',
    '// Minor-unit digits per currency – the same table as the apps (minorDigits) and Saldo\'s server.',
    `export const ISO_CURRENCY_DIGITS = Object.freeze(${JSON.stringify(sorted, null, 2)});`,
    '',
  ].join('\n');
}

/** Saldo's server table, or null (repo or file not here). */
function saldoTable() {
  if (!fs.existsSync(path.join(saldoRepo, '.git'))) return null;
  for (const ref of saldoRefs) {
    try {
      const text = execFileSync('git', ['-C', saldoRepo, 'show', `${ref}:${SALDO_FILE}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
      return { ref, digits: JSON.parse(text).digits };
    } catch {}
  }
  return null;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const wanted = currencyDigitsModule();
  const target = path.join(root, TARGET);
  if (!process.argv.includes('--check')) {
    fs.writeFileSync(target, wanted);
    console.log(`Wrote ${TARGET} from app-core (${Object.keys(ISO_CURRENCY_DIGITS).length} currencies).`);
  } else {
    const copy = fs.existsSync(target) ? lf(fs.readFileSync(target, 'utf8')) : null;
    if (copy !== wanted) {
      console.error(`Currency digits: ${TARGET} differs from app-core ISO_CURRENCY_DIGITS – run node scripts/sync-currency-digits.mjs`);
      process.exit(1);
    }
    const saldo = saldoTable();
    if (!saldo) {
      console.log(`Currency digits OK (same as app-core). Saldo's ${SALDO_FILE} is not here – not compared.`);
    } else {
      const differs = Object.entries(saldo.digits).filter(([c, d]) => ISO_CURRENCY_DIGITS[c] !== d).map(([c]) => c);
      if (differs.length) {
        console.error(`Currency digits: ${TARGET} differs from Saldo ${saldo.ref}:${SALDO_FILE} for ${differs.join(', ')} – update app-core in vendor/ and run node scripts/sync-currency-digits.mjs`);
        process.exit(1);
      }
      console.log(`Currency digits OK (same as app-core and Saldo ${saldo.ref}).`);
    }
  }
}
